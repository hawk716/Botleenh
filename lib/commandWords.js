const EXACT = new Set(COMMAND_WORDS);

// أول كلمة من كل أمر — للأوامر التي تتبعها كلمات أخرى مثل: 'اغنية محمد'
// (نستثني الكلمات ذات الحرف الواحد حتى لا نعتبر كل رسالة تبدأ بـ "م" أمراً)
const FIRST = new Set(
    COMMAND_WORDS.filter(w => w.length > 1).map(w => w.split('_')[0])
);

const clean = (t) => String(t || '')
    .trim()
    .replace(/^\.+/, '')
    .replace(/\s+/g, ' ');

// تطبيع إملائي: يحذف "ال" التعريف ويوحّد الهمزات والتاء المربوطة والألف المقصورة
// حتى لا يفلت المحظور بكتابة "الاخبار" بدل "اخبار" أو "نسبة" بدل "نسبه"
const canon = (w) => String(w)
    .replace(/[\u064B-\u0652\u0640]/g, '')
    .replace(/[\u0623\u0625\u0622\u0671]/g, '\u0627')
    .replace(/\u0649/g, '\u064A')
    .replace(/\u0626/g, '\u064A')
    .replace(/\u0624/g, '\u0648')
    .replace(/\u0629/g, '\u0647')
    .replace(/^\u0627\u0644/, '');

const CANON_FIRST = new Set([...FIRST].map(canon));

function isBotCommand(text) {
    const t = clean(text);
    if (!t) return false;

    const tU = t.replace(/\s+/g, '_');
    if (EXACT.has(tU)) return true;

    const first = t.split(' ')[0];
    if (FIRST.has(first)) return true;
    if (CANON_FIRST.has(canon(first))) return true;

    return false;
}

module.exports = { COMMAND_WORDS, isBotCommand };
