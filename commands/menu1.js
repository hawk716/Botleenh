async function menu1Command(sock, chatId, message) {
    const menuMessage = `*↢ اوامــر الادارة*
─────────────────────
*↢ اوامــر الـرفـع والتنـزيـل*
─────────────────────
*↢ رفع ↢ ادمن بكامل الصلاحيات*
*↢ رفع ↢ مالك*
*↢ رفع - تنزيل ↢ مدير*
*↢ رفع - تنزيل ↢ ادمن*
*↢ رفع - تنزيل ↢ مميز*
*↢ الرتبة ↢ عرض رتبة العضو*
*↢ عدد الرتب ↢ إحصائيات بالعدد*
*↢ كشف الرتب ↢ إحصائيات عام*
─────────────────────
*↢ اوامــر المســح*
─────────────────────
*↢ مسح ↢ حذف رسالة*
*↢ مسح الكل ↢ مسح جميع الرتب*
*↢ مسح المدراء*
*↢ مسح الادمنيه*
*↢ مسح المميزين*
*↢ مسح المحظورين*
*↢ مسح المقيدين*
*↢ مسح الإنذارات للكل*
─────────────────────
*↢ اوامــر الحظـر،الكتـم،التقييـد*
─────────────────────
*↢ حظر - الغاء الحظر*
*↢ طرد*
*↢ تقييد - الغاء التقييد*
*↢ تقييد + الوقت*
*↢ انذار - انذار + العدد*
*↢ الإنذارات*
*↢ إنذاراتي*
*↢ مسح الإنذارات*`;

    try {
        await sock.sendMessage(chatId, { text: menuMessage }, { quoted: message });
    } catch (error) {
        console.error('Error in menu1 command:', error);
        await sock.sendMessage(chatId, { text: menuMessage }, { quoted: message });
    }
}

module.exports = menu1Command;
