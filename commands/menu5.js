async function menu5Command(sock, chatId, message) {
    const menuMessage = `*↢ قائمة الاوامر المتنوعة*
─────────────────────
*↢ اوامــر عامــة*
*↢ بينغ*
*↢ نشط*
*↢ عرض مره*
*↢ رابط قصير*
─────────────────────
*↢ اوامــر التحميــل*
*↢ اغنية*
*↢ فيديو*
*↢ انستقرام*
*↢ قصص انستا*
*↢ فيسبوك*
*↢ تيك توك*
*↢ سبوتيفاي*
*↢ كلمات الاغنية + اسم الاغنية*
─────────────────────
*↢ اوامــر الصــور والملصقــات*
*↢ ملصق*
*↢ صوره*
*↢ نص لملصق*
*↢ قص ملصق*
*↢ ملصقات تيليجرام*
*↢ تغيير اسم الملصق*
*↢ دمج ايموجي*
*↢ تمويه*
*↢ ازالة الخلفية*
*↢ تحسين*
*↢ لقطة شاشة*
─────────────────────
*↢ اوامــر المعلومات*
*↢ طقس + اسم المدينه*
*↢ جو*
*↢ اخبار*
*↢ اخبار عربية*
*↢ اعلى الاعضاء*
─────────────────────
*↢ اوامــر الذكــاء الاصطناعــي*
*↢ جبتي + طلبك*
*↢ جيمني + طلبك*
*↢ ميتا + طلبك*
*↢ انشاء صوره*
*↢ توليد صوره*
*↢ انشاء فيديو*
*↢ توليد فيديو*
*↢ ترجم*
*↢ نص صوتي*
*↢ نطق النص*
*↢ نص الى صوت*`;

    try {
        await sock.sendMessage(chatId, { text: menuMessage }, { quoted: message });
    } catch (error) {
        console.error('Error in menu5 command:', error);
        await sock.sendMessage(chatId, { text: menuMessage }, { quoted: message });
    }
}

module.exports = menu5Command;