async function menu3Command(sock, chatId, message) {
    const menuMessage = `*↢ اوامــر الوضــع والاضافــات*
─────────────────────
*↢ التحـكم بـالاوامـر*
*↢ تغيير امر*
*↢ حذف امر*
*↢ الاوامر المضافه*
*↢ مسح الاوامر المضافه*
─────────────────────
*↢ التحـكم بالاشتـراك الاجبـاري*
*↢ اضف اشتراك*
*↢ حذف اشتراك*
*↢ عرض الاشتراك*
─────────────────────
*↢ التحـكم بـالمنـع*
*↢ منع ↢بالرد على كلمة*
*↢ الغاء منع*
*↢ قائمة المنع*
*↢ مسح قائمه المنع*
─────────────────────
*↢ اوامــر المــنــشــن*
*↢ منشن*
*↢ منشن الكل*
*↢ منشن مخفي*
*↢ منشن الاعضاء*
─────────────────────
*↢ اوامــر وضــع المجـمـوعــة*
*↢ اسم القروب + الاسـم*
*↢ صوره القروب ↢بالرد - بالتعليق*
*↢ وصف القروب + الوصف*
*↢ مسح الوصف*
*↢ ضع ترحيب*
*↢ ضع وداع*
*↢ مسح الترحيب*
*↢ الترحيب*
*↢ اضف رد*
*↢ مسح رد + الـرد*
*↢ الردود*
*↢ القوانين*
*↢ الرابط*
*↢ معلومات المجموعه*
*↢ مسح القوانين*
*↢ تثبيت + الكلمة - بالـرد*
*↢ الغاء تثبيت ↢بالـرد*
*↢ الغاء المثبت*
*↢ ضع لقب + اللقب ↢بالـرد*`;

    try {
        await sock.sendMessage(chatId, { text: menuMessage }, { quoted: message });
    } catch (error) {
        console.error('Error in menu3 command:', error);
        await sock.sendMessage(chatId, { text: menuMessage }, { quoted: message });
    }
}

module.exports = menu3Command;