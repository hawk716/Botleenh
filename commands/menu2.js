
async function menu2Command(sock, chatId, message) {
    const menuMessage = `*↢ اوامر القفل والفتح*
─────────────────────
↢ قفل - فتح الروابط  
↢ قفل - فتح التاك
↢ قفل - فتح التثبيت
↢ قفل - فتح المتحركه
↢ قفل - فتح الصور
↢ قفل - فتح الملصقات
↢ قفل - فتح الملفات
↢ قفل - فتح الفيديو
↢ قفل - فتح التوجيه
↢ قفل - فتح الصوت
↢ قفل - فتح الفويس
↢ قفل - فتح الجهات
↢ قفل - فتح الوسائط
↢ قفل - فتح التعديل
↢ قفل - فتح الكل
↢ قفل - فتح القروب (بدون مدة)
─────────────────────
*↢ اوامر التعطيل والتفعيل*
─────────────────────
↢ تفعيل - تعطيل الترحيب
↢ تفعيل - تعطيل الردود
↢ تفعيل - تعطيل الرفع
↢ تفعيل - تعطيل الايدي
↢ تفعيل - تعطيل الحظر
↢ تفعيل - تعطيل التحميل
↢ تفعيل - تعطيل الرابط
↢ تفعيل - تعطيل اطردني
↢ تفعيل - تعطيل نزلني
↢ تفعيل - تعطيل المنشن
↢ تفعيل - تعطيل الالعاب
↢ تفعيل - تعطيل انذار
↢ تفعيل - تعطيل الاوامر
↢ تفعيل - تعطيل اكتموه
↢ تفعيل - تعطيل نداء المالك
─────────────────────
*↢ اوامر القفل الإختياريـة*
─────────────────────
↢ قفل امر ↢ اسـم الامـر
↢ فتح امر ↢ اسـم الامـر
─────────────────────
*↢ اوامر الإعـدادات*
─────────────────────
↢ الاعدادات
↢ اعدادات المنشن`;

    try {
        await sock.sendMessage(chatId, { 
            text: menuMessage
        }, { quoted: message });
    } catch (error) {
        console.error('Error in menu2 command:', error);
        await sock.sendMessage(chatId, { text: menuMessage }, { quoted: message });
    }
}

module.exports = menu2Command;
